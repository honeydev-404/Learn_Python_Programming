#Variables are the data container that we can use to store the data, and use or call it with its name (like - name = "Honey").

player_health = 100 # This is the variable(player_health).
print("Initial Player Health:-", player_health) # Here when we place the variable name it will be called by the print function.

# We can also change the value of the variable by calling it again with different values, so the function which are using it will use the latest assigned value.

player_health = 75
print("Player's Health After Taking Damage:-", player_health) # See the variable name was same but its value changed so we got different result with same variable name.
