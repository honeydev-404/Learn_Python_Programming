#The BIT (Binary Digit) :- It is the smallest unit of data in computing, it is just electric switch like 0(off) and 1(on).

#The BYTE :- A combined group of 8 bits acting together making a byte (e.g., 10110100), a single byte can represent positive integers between 0 and 255.

#How Data Scales (Base-2 maths) :-
# 1 Bit = A single 0 or 1.
# 1 Byte = 8 bits.
# 1 Kilobyte = 1024 bytes
# 1 megabyte = 1024 kilobytes
# 1 gigabyte = 1024 megabytes

#Code proving it...
