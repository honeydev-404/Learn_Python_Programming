# Now we will study about the conditional operatiors that are answered in True or False.

num1 = 10
num2 = 20

num2 < num1 #Checks if num2 is smaller than num1.
num1 > num2 #Checks if the num1 is greater than num2.
num1 >= num2 #Checks if the num1 is greater than or equals to num2.
num2 <= num1 #Checks if the num2 is smaller than or equals to num1.
num1 == num2 #Checks if the num1 is equals to num2.
num1 != num2 #Checks if the num1 is not equals to num2 (! means not/opposite action).

#Remember -> There is a very critical difference between single equals-to(=) and double equals-to(==) that most of the beginners miss. = is used for assignment of value to a variable and == is used when we want to compare 2 values.
 