# So, now you know how to store variables now lets interact with them mathematically.

# Dynamic Arithmetic -> You can add, subtract, divide or multiply variables together normally.
num1 = 100
num2 = 25
total_sum = num1 + num2
print("The Total Sum of number 1 and 2 is", total_sum)

#In-Place Operators(shorthand) -> Now you must have seen that the code above was very long, so the shorthand comes in which helps us to make our work easier. Lets understand it with the help of code.
gold_coin = 10 
#gold_coin = gold_coin + 10 -> So here I have to write more code, so for solving this problem we introduce you shorthand.

gold_coin += 10 #So this is the solution of the problem of the above line and this is the shorthand method.
print("Total Gold Coins are", gold_coin)

