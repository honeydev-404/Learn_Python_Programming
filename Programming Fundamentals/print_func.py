# Now I will show you some magic by print not only string but numbers, boolean values and also decimal values.

print("Hello World!") # This will print Hello World! (String).
print(72) # This will print 72 (Integer).
print(92.34) # This will print 92.34 (Float)
print(True) # This will print True (Boolean). 

# We can also use concatenation(joining string with string) to print two different value seprately.

print("Python is", "Great") # This will print Python is Great, this is called string concatenation.
print("The latest version of python is", 3.15) # This will print The latest version of python is 3.15, This is not exactly concatenation
print("My age is", 15) # Same as above but it will print an intege value with string. This is not also exactly concatenation.

# We can also perform mathematical operation.

print(20 + 10) # This will print 30 as it is the sum of 20 and 10.
