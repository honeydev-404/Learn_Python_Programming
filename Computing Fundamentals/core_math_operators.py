num1 = 20
num2 = 30

#Arithemetic Operators:-
sum = num1 + num2 #For Addition.
print(sum)

sub = num1 - num2 #For Subtraction.
print(sub)

div = num1 / num2 #For Division.
print(div)

flr_div = num1 // num2 #For Floor-Division(tell the value before the decimal).
print(flr_div)

rema = num1 % num2 #For finding out the remainder.
print(rema)

mul = num1 * num2 #For multiplication.
print(mul)

power = num1 ** num2 #Here num2 will work as power for num1.
print(power)

#Relational/Comparison Operators:- (Remember these returns the value in True/False).
equal_to = num1 == num2 #If num1 is equal to num2.
print(equal_to)

not_equal_to = num1 != num2 #If num1 is not equal to num2.
print(not_equal_to)

greater_than_or_equal_to = num1 >= num2 #If num1 is greater than or equal to num2.
print(greater_than_or_equal_to)

less_than_or_equal_to = num1 <= num2 #if num1 is smaller than or equal to num2.
print(less_than_or_equal_to)

#Assignment Operators (shortcut):-

num1 += 10 #It adds 10 to the num1 variable.
print(num1)

num1 -= 10 #It subtracts 10 to the num1 varible.
print(num1)

num1 *= 10 #Multiply.
print(num1)

num1 /= 10 #Divide.
print(num1)

num1 %= 10 #Remainder
print(num1)

num1 **= 10 #Power (^).
print(num1)

